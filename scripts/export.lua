-- Override hard-coded syntax colors in the original Solitude stylesheet.
local syntax = {
  { "comment,prolog,doctype,cdata", ".cm-comment", "comment" },
  { "keyword,tag,atrule", ".cm-keyword, .cm-atom", "keyword" },
  { "string,char,attr-value", ".cm-string", "string" },
  { "function,class-name", ".cm-def", "function" },
  { "number,boolean,constant,symbol", ".cm-number, .cm-bool, .cm-constant", "value" },
  { "property,attr-name", ".cm-property", "property" },
  { "operator", ".cm-operator", "operator" },
  { "punctuation", ".cm-punctuation", "punctuation" },
}
for _, rule in ipairs(syntax) do
  local tokens = {}
  for token in rule[1]:gmatch("[^,]+") do
    tokens[#tokens + 1] = ".token." .. token
  end
  css[#css + 1] = ".theme-dark .markdown-rendered pre code :is(" .. table.concat(tokens, ", ") .. "),"
  css[#css + 1] = ".theme-dark .cm-s-obsidian :is(" .. rule[2] .. ") {"
  css[#css + 1] = "  color: var(--code-" .. rule[3] .. ");"
  css[#css + 1] = "}"
end
css[#css + 1] = ".theme-dark .cm-s-obsidian .cm-variableName { color: var(--text-muted); }"
css[#css + 1] = ".theme-dark .view-header-title::selection { background-color: var(--text-selection); color: var(--text-normal); }"
write("extras/obsidian/solitude-palette.css", css)
