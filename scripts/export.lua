-- Run from the repository root: nvim --headless -u NONE -l scripts/export.lua
local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")
vim.opt.runtimepath:prepend(root)
local p = require("solitude.palette")
local ansi = require("solitude.terminal")

local function write(path, lines)
  local full = root .. "/" .. path
  vim.fn.mkdir(vim.fn.fnamemodify(full, ":h"), "p")
  assert(vim.fn.writefile(lines, full) == 0, "Could not write " .. full)
  print("Generated " .. path)
end

local kitty = { "# Generated by scripts/export.lua; edit lua/solitude/palette.lua." }
local roles = {
  { "background", p.bg }, { "foreground", p.fg },
  { "cursor", p.fg }, { "cursor_text_color", p.bg },
  { "selection_background", p.selection }, { "selection_foreground", "none" },
  { "active_border_color", p.sand }, { "inactive_border_color", p.border },
  { "active_tab_foreground", p.fg }, { "active_tab_background", p.bg_active },
  { "inactive_tab_foreground", p.fg_faint }, { "inactive_tab_background", p.bg_surface },
  { "tab_bar_background", p.bg_surface }, { "url_color", p.red },
}
for _, role in ipairs(roles) do
  kitty[#kitty + 1] = role[1] .. " " .. role[2]
end
for slot = 0, 15 do
  kitty[#kitty + 1] = "color" .. slot .. " " .. ansi[slot]
end
write("extras/kitty/solitude.conf", kitty)

